/*
 * Matrix Music — 大面板（large）运行时配置
 *
 * 在 constants.js 之后、其余脚本之前加载，把 TM.RUNTIME 覆盖成 48 行 × 64 列。
 * **只有 large.html 引入它**；index.html 不加载，因此基准版 16×16 逐位不变。
 *
 * 这里只覆盖「与基准版不同」的项 —— 没写的（inset / radius / blurCell /
 * 描边参数等）一律自动回落 CONFIG.*。
 */
(function (global) {
  'use strict';

  var TM = global.TM;
  var R = TM.RUNTIME;

  var COLS = 1024;               // 时间步（**数据宽度**，视口只显示其中一段）
  var ROWS = 48;                 // 音高行数 = 半音阶 47 个半音（A7 → A#3）
  // 格子边长 = 基准版。方块因此是 32 − 2 × 3 = 26px，与基准版**逐像素同尺寸**。
  //
  // 代价是画布变成 64×48 × 32px = 2048 × 1536：既超出笔记本横向视口，
  // 也远超其纵向视口（48 行 × 26px 光棋盘就有 1536px 高）。这是几何决定的，
  // 想同时要「大盘面」和「基准版大小的方块」就必然要滚动 —— 所以布局改成
  // 不缩放、可滚动（见 style.css 的 body.wide / .stage-wide），
  // 方块保持 1:1 上屏，浏览器不做二次重采样。
  //
  // 曾经试过把格子减半到 16px 来塞进屏幕，但那样按比例算出的内缩是 1.5，
  // 在 1x 屏上方块边界落在半像素、被抗锯齿糊出灰边（实测过渡值 25 / 119，
  // 整数内缩下灰度只出现 0 / 51 / 238 三个值）。既然要跟基准版一样大，
  // 索性连格子尺寸一起沿用基准版，这条坑也就不存在了。
  var CELL = TM.CONFIG.CELL;

  // 面板身份。**注意它不带尺寸** —— 存档键是 matrixmusic.score.large，
  // 以后再加/减八度，键不变，用户存在本机的那份谱子会自动接着用。
  R.id = 'large';
  // 横向可平移：数据比视口宽，画布只渲染可见列（见 renderer 的 viewCol0/viewCols）。
  // 基准版不开，保持 16 × 16 定宽。
  R.scrollX = true;
  R.cols = COLS;
  R.rows = ROWS;
  R.cell = CELL;

  // ── 音阶：半音阶（相邻行差 1 个半音，像吉他每格一品）──
  // 48 行覆盖 47 个半音（将近 4 个八度）：行 0 = A7 = 基准版最高音再高一个八度，
  // 往下一直铺到 A#3。基准版 16 行的音域（A6 → A3）几乎完整落在这张表里，
  // 只是把中间的音填满了 —— 中段仍与基准版的中音区重合。
  //
  // 往上加一个八度 = TOP + 12、ROWS + 12，**底部不动**，
  // 所以旧表（96..61）正好落在新表的行 12..47。
  var TOP = TM.CONFIG.NOTES[0] + 12;       // 108 = A7（基准版最高音 + 一个八度）
  R.notes = TM.buildScaleTable(ROWS, TOP, TM.SCALES.chromatic);   // A7 → A#3

  // 注意：基准版 16 行是五声、这里是半音阶，所以**没有「行号平移对应」关系** ——
  // 同一份图案搬过来音高会变。但半音阶是任何音阶的超集：基准版每个音都能在这张
  // 表里找到（只是行号不同），test/large.html 有断言守着这条。

  // ── 微光 ───────────────────────────────────────────────
  // 光晕层**刻意远低于画布分辨率**：512 × 384（画布是 2048 × 1536），合成时放大 4×。
  // 它本来就要被大半径模糊，按画布分辨率渲染纯属浪费面积。
  //
  // blurGlow = 3：这里一个光晕格 = 512 / 64 = 8px，基准版是 512 / 16 = 32px、
  // 模糊 12。取 8 × 12/32 = 3，两版的光相对网格的柔和程度就一致。
  //
  // 尺寸只影响成本、不影响观感：实测 1024 时每帧 5.3 ms，512 只要 1.2 ms，
  // 两者放大到画布上肉眼看不出差别（模糊半径已按格宽等比缩放）。
  R.glowSize = 512;
  R.blurGlow = 3;

  // ── 布局 ───────────────────────────────────────────────
  // 画布的 CSS 尺寸 = 逻辑尺寸（不是设备尺寸），这样无论 dpr 多少都是 1:1 上屏。
  // 写成 CSS 变量给 style.css 用，避免在样式表里硬编码 2048 / 1024。
  var root = global.document.documentElement;
  // 宽度由 app.js 按视口算出来再写（--board-w = 视口像素宽）。这里先给个中性值，
  // 避免脚本执行前按 32768px 排一次版再跳回来。
  root.style.setProperty('--board-w', '100%');
  root.style.setProperty('--board-h', (ROWS * CELL) + 'px');
})(window);
